"""Write solvers.ts mechanically from ../benchmark/bench.ts (Round 3 task 4). No hand edits.

bench.ts runs its benchmark when imported, so its instance generator and its 25 solver functions are copied
(lines from "// ---- deterministic instances ----" to the line before "// ---- harness ----") with an export line.
The integrated suite cross-checks the copy against the Round 2 record (accepted-at-zero-gap counts per version).
"""
from pathlib import Path
import hashlib

here = Path(__file__).resolve().parent
src = (here.parent / 'benchmark/bench.ts').read_text()
a, b = src.index('// ---- deterministic instances ----'), src.index('// ---- harness ----')
head = ('// GENERATED by extract_solvers.py from ../benchmark/bench.ts (sha256 ' + hashlib.sha256(src.encode()).hexdigest() + '). Do not edit.\n'
        '// UNTRUSTED code: instance generator, brute-force reference and 25 solver functions.\n'
        'export type Instance = { name: string; kind: "interval" | "general"; A: number[][]; c: number[]; w: number[] };\n'
        'export type Witness = { x: number[]; y: number[]; z: number[] };\n')
(here / 'solvers.ts').write_text(head + src[a:b] + 'export { instances, V, feasible, value, bruteOpt };\nexport type { Version };\n')
print('solvers.ts written,', len(src[a:b].splitlines()), 'lines copied')
