"""Build replay sources for the published backendProof$compile_correct'. The published file is read only.

Usage: python3 -I -B make_cc.py control <out.sml>
       python3 -I -B make_cc.py variant <out.sml> <tail.sml> [show]

control: the published statement and proof text, lines 4007-4921, unchanged.
variant: the same proof text with recorded edits: the conclusion carries a guard set, and
         the last four tactic lines of the stack_init part are replaced by <tail.sml>.
"""
import sys, hashlib
PUB = '/Users/mackianni/forge/.toolchain/experiments/refund-cakeml-20261104/cakeml/compiler/backend/proofs/backendProofScript.sml'
raw = open(PUB, 'rb').read()
assert hashlib.sha256(raw).hexdigest().startswith('380ee3fa'), 'published script changed'
L = raw.decode().split('\n')
def lines(a, b): return '\n'.join(L[a - 1:b])
def need(c, m):
    if not c: raise SystemExit('edit site check failed: ' + m)
need(L[4006] == "Theorem compile_correct':", 'theorem start')
need(L[4920] == "Finalise compile_correct';", 'theorem end')
need(L[3983].startswith('Theorem word_init_compile_oracle[local]'), 'local oracle lemma')
need(L[4004] == 'QED', 'local oracle lemma end')
need(L[2987].startswith('Theorem FST_SND_EQ[local]'), 'local pair lemma')
need(L[3000] == 'QED', 'local perm lemma end')
need(L[198].startswith('Overload bvl_inline_compile_prog[local]'), 'overloads start')
need(L[222].startswith('Overload no_mti[local]'), 'overloads end')
need(L[612].startswith('val [source_to_flat_orac_eq'), 'orac eqs')
need(L[821].startswith('fun conseq'), 'helpers')
need(L[1570].startswith('val EVAL = computeLib.RESTR_EVAL_CONV'), 'EVAL')
need(L[1582].startswith('fun specl_compile_args_of_then'), 'specl')
mode, out = sys.argv[1], sys.argv[2]
thy = {'control': 'forge_compileCorrectControl', 'variant': 'forge_compileCorrectLabFacts'}[mode]
HEAD = '''(* Generated by make_cc.py (%s). Published text: backendProofScript.sml, SHA256 prefix 380ee3fa. *)
open preamble
open wordSemTheory primSemEnvTheory semanticsPropsTheory backendTheory source_to_sourceProofTheory
     source_to_flatProofTheory flat_to_closProofTheory clos_to_bvlProofTheory bvl_to_bviProofTheory
     bvi_inlineProofTheory bvi_to_dataProofTheory data_to_wordProofTheory data_to_word_syntaxProofTheory
     word_to_stackProofTheory stack_to_labProofTheory lab_to_targetProofTheory backend_commonTheory
     backendPropsTheory word_to_stackTheory backendProofTheory;
val _ = Globals.max_print_depth := 80;
fun pr s = print (s ^ "\\n");
fun tags name th = let val (ors,axs) = Tag.dest_tag (Thm.tag th) in
  if null (hyp th) andalso null axs andalso List.all (fn x => x = "DISK_THM") ors then ()
  else raise Fail ("Unexpected assumptions: " ^ name ^ " oracles=" ^ String.concatWith "," ors) end;
fun show_tac tag (g as (asl, w)) = (pr ("SHOW " ^ tag);
   List.app (fn a => let val t = term_to_string a in pr ("  ASM " ^ String.substring (t, 0, Int.min (700, size t))) end) asl;
   pr ("  GOAL " ^ String.substring (term_to_string w, 0, Int.min (2500, size (term_to_string w)))); ALL_TAC g);
val _ = OS.FileSys.chDir (valOf (OS.Process.getEnv "FORGE_P3_OUT"));
val _ = new_theory "%s";
(* Published context, lines 17-25. *)
''' % (mode, thy) + lines(17, 19) + '''
val _ = Parse.set_grammar_ancestry
  [ "backend", "backend_common", "backendProps",
    "primSemEnv", "semanticsProps",
    "labProps",
    "source_evalProof", "backendProof"
  ];
(* Published local overloads, lines 199-223. *)
''' + lines(199, 223).replace('[local]', '') + '''
(* Published ML bindings, lines 613-619, 822-827, 1571-1573, 1583-1592. *)
''' + lines(613, 619) + '\n' + lines(822, 827) + '\n' + lines(1571, 1573) + '\n' + lines(1583, 1592) + '''
(* Published local lemmas, lines 2988-3001 and 3984-4005. *)
''' + lines(2988, 3001) + '\n' + lines(3984, 4005) + '\n'
body = lines(4007, 4921)
if mode == 'control':
    TAIL = '''
val pub = DB.fetch "backendProof" "compile_correct'";
val mine = DB.fetch "forge_compileCorrectControl" "compile_correct'";
val _ = tags "compile_correct'" mine;
val _ = if aconv (concl pub) (concl mine) andalso null (hyp mine) then pr "CONTROL_IDENTICAL_STATEMENT true"
        else raise Fail "replayed statement differs from the published one";
val _ = pr ("CHECKED compile_correct'\\n" ^ thm_to_string mine);
val closure = "forge_compileCorrectControl" :: Theory.ancestry "forge_compileCorrectControl";
val _ = pr ("CLOSURE_NODES " ^ Int.toString (length closure));
val _ = pr ("CLOSURE_PARENTS " ^ String.concatWith " " (Theory.parents "forge_compileCorrectControl"));
val _ = List.app (fn n => List.app (fn (a,_) => pr ("CLOSURE_AXIOM " ^ n ^ "." ^ a)) (DB.axioms n)) closure;
val _ = export_theory ();
val _ = pr "REPLAY_COMPLETE";
val _ = OS.Process.exit OS.Process.success;
'''
    src = HEAD + body + '\n' + TAIL
else:
    PRE = open('variant-pre.sml').read()
    POST = open('variant-post.sml').read()
    tail = open(sys.argv[3]).read()
    old_stmt = '''     machine_sem (mc:(α,β,γ) machine_config) ffi ms ⊆
       extend_with_resource_limit\''''
    need(body.count(old_stmt) == 1, 'conclusion site')
    body = body.replace(old_stmt, '''     lab_guard (machine_sem (mc:(α,β,γ) machine_config) ffi ms) (lab_facts asm_conf c prog bytes c' mc ffi ms cbspace) ⊆
       extend_with_resource_limit\'''')
    old_tail = lines(4817, 4822)
    need(old_tail.startswith("  match_mp_tac implements'_strengthen \\\\ qexists_tac `T`"), 'tail site')
    need(body.count(old_tail) == 1, 'tail site count')
    body = body.replace(old_tail, tail)
    keep_site = lines(4197, 4197)
    need(keep_site.startswith("  `SND(to_data c prog) = p4 /\\ SND(to_word mc.target.config c prog) = p5` by"), 'marker site')
    need(body.count(keep_site) == 1, 'marker site count')
    body = body.replace(keep_site, """  `lab_keep_word mc.target.config c prog p5` by
    (rewrite_tac [lab_keep_word_def] \\\\
     fs[to_word_def,to_data_def,to_bvi_def,to_bvl_def,to_clos_def,to_flat_def]) \\\\
""" + keep_site)
    body = body.replace("compile_correct'", 'compile_correct_lab_guard')
    src = HEAD + PRE + '\n' + body + '\n' + POST
open(out, 'w').write(src)
