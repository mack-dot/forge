"""Generate the boundary-witness lemmas and the receipt for the refund-cap spec diff (U418) from ONE table.

Output: SpecDiffRefundCapWitnesses.dfy (checked by the pinned Dafny) and records/refund-cap-receipt.json (data only).
The capped specification is a fixture, not a proposed change. No timestamps.
"""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
W = [  # name, title, original, remaining, enabled, open, response (None = Missing | (amount, reason)), kind, old, new
    ('R1', 'amount exactly at the cap', 100, 100, True, True, (50, 'duplicate_charge'), 'unchanged', 'Authorized', 'Authorized'),
    ('R2', 'amount one above the cap', 100, 100, True, True, (51, 'duplicate_charge'), 'newly_rejected', 'Authorized', 'Rejected'),
    ('R3', 'odd original, amount at half rounded up', 101, 101, True, True, (51, 'returned_item'), 'newly_rejected', 'Authorized', 'Rejected'),
    ('R4', 'full refund of the original', 100, 100, True, True, (100, 'service_not_delivered'), 'newly_rejected', 'Authorized', 'Rejected'),
    ('R5', 'zero amount', 100, 100, True, True, (0, 'duplicate_charge'), 'unchanged', 'Authorized', 'Authorized'),
    ('R6', 'reason not allowed', 100, 100, True, True, (10, 'goodwill'), 'unchanged', 'Rejected', 'Rejected'),
    ('R7', 'model response missing', 100, 100, True, True, None, 'unchanged', 'Rejected', 'Rejected'),
    ('R8', 'refunds disabled', 100, 100, False, True, (10, 'duplicate_charge'), 'unchanged', 'Rejected', 'Rejected'),
]
out = ['// GENERATED by gen_refund_witnesses.py (U418). Do not edit. Boundary witnesses for the refund-cap spec diff.',
       '// Each lemma: EVERY result that the approved specification allows and EVERY result that the capped variant',
       '// allows for this input are the stated ones; and both allow a result (non-vacuity).',
       'include "SpecDiffRefundCap.dfy"', '', 'abstract module SpecDiffRefundCapWitnesses {', '  import D : SpecDiffRefundCap', '']
rows = []
def b(x): return 'true' if x else 'false'
for name, title, orig, rem, en, op, resp, kind, od, nd in W:
    C = f'D.O.ChargeContext("ch_1", "rq_1", {orig}, {rem}, {b(en)}, {b(op)})'
    R = 'D.O.Missing' if resp is None else f'D.O.Candidate({resp[0]}, "{resp[1]}")'
    olddec = f'D.O.Authorized({resp[0]}, "{resp[1]}")' if od == 'Authorized' else 'D.O.Rejected'
    newdec = f'D.N.Authorized({resp[0]}, "{resp[1]}")' if nd == 'Authorized' else 'D.N.Rejected'
    call = (f'D.NewlyRejectedAboveTheCap({C}, {R}, d, p, d\', p\');' if kind == 'newly_rejected'
            else f'D.UnchangedOutsideTheCap({C}, {R}, d, p, d\', p\');\n    D.PostOCases({C}, {R}, d, p);')
    elig = 'true' if od == 'Authorized' else 'false'
    out += [f'  // {name}: {title}. Kind: {kind}.',
            f'  lemma {name}(d: D.O.Decision, p: seq<D.O.RefundIntent>, d\': D.N.Decision, p\': seq<D.N.RefundIntent>)',
            f'    requires D.PostO({C}, {R}, d, p)',
            f'    requires D.PostN(D.CtxN({C}), D.RespN({R}), d\', p\')',
            f'    ensures d == {olddec} && |p| == {1 if od == "Authorized" else 0}',
            f'    ensures d\' == {newdec} && |p\'| == {1 if nd == "Authorized" else 0}',
            '  {',
            f'    assert D.O.Eligible({C}, {R}) == {elig};',
            f'    {call}',
            '  }', '',
            f'  lemma {name}_NonVacuous()',
            f'    ensures exists d: D.O.Decision, p: seq<D.O.RefundIntent> :: D.PostO({C}, {R}, d, p)',
            f'    ensures exists d\': D.N.Decision, p\': seq<D.N.RefundIntent> :: D.PostN(D.CtxN({C}), D.RespN({R}), d\', p\')',
            '  {',
            f'    D.OldPostSatisfiable({C}, {R});',
            f'    D.NewPostSatisfiable(D.CtxN({C}), D.RespN({R}));',
            '  }', '']
    rows.append({'witness': name, 'title': title, 'kind': kind,
                 'context': {'original': orig, 'remaining': rem, 'refundEnabled': en, 'requestOpen': op},
                 'response': 'Missing' if resp is None else {'amount': resp[0], 'reason': resp[1]},
                 'approved_spec': od, 'capped_variant': nd,
                 'dafny_lemmas': [f'SpecDiffRefundCapWitnesses.{name}', f'SpecDiffRefundCapWitnesses.{name}_NonVacuous']})
out.append('}')
(HERE / 'SpecDiffRefundCapWitnesses.dfy').write_text('\n'.join(out) + '\n')
receipt = {'change': 'approved spec/refund/RefundSpec.dfy versus fixtures/RefundSpecCapped.dfy (variant: amount * 2 <= original)',
           'status': 'DATA ONLY. The capped specification is a fixture, not a proposed change. Each row and statement is a Dafny lemma.',
           'end_to_end': False,
           'general_statements': [
               {'lemma': 'SpecDiffRefundCap.EligibleNewIff', 'text': 'Eligible under the variant exactly when eligible under the approved spec and amount * 2 <= original.'},
               {'lemma': 'SpecDiffRefundCap.UnchangedOutsideTheCap', 'text': 'Unchanged region: every input the approved spec rejects, and every eligible input within the cap. Same decision and plan.'},
               {'lemma': 'SpecDiffRefundCap.NewlyRejectedAboveTheCap', 'text': 'Changed region: eligible and above the cap. The approved spec authorizes; the variant rejects with an empty plan.'},
               {'lemma': 'SpecDiffRefundCap.OldDeterministic, NewDeterministic', 'text': 'Both specifications allow at most one result per input.'},
               {'lemma': 'SpecDiffRefundCap.OldPostSatisfiable, NewPostSatisfiable', 'text': 'Both allow a result for every input.'}],
           'boundary_witnesses': rows}
(HERE / 'records/refund-cap-receipt.json').write_text(json.dumps(receipt, indent=1, sort_keys=True) + '\n')
print(len(rows), 'witnesses written')
