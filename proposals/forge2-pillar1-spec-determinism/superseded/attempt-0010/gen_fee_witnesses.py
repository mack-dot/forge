"""Generate the boundary-witness lemmas and the receipt for the fee-change spec diff (U413) from ONE table.

Output: SpecDiffFeeWitnesses.dfy (checked by the pinned Dafny) and records/fee-change-receipt.json (data only).
The receipt proves nothing by itself: each row is a lemma that Dafny must verify. No timestamps.
Usage: python3 -I -B gen_fee_witnesses.py
"""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
ID = 7
W = [  # name, title, balances, accepted {id: (s, r, amt)}, (sender, recipient, amount), kind, old (outcome, balances), new (outcome, balances)
    ('W1', 'sender balance equals the amount', {0: 0, 1: 5, 2: 0}, {}, (1, 2, 5), 'newly_rejected',
     ('Ok', {0: 0, 1: 0, 2: 5}), ('Rejected', {0: 0, 1: 5, 2: 0})),
    ('W2', 'sender balance equals the amount plus one', {0: 0, 1: 5, 2: 0}, {}, (1, 2, 4), 'both_accept',
     ('Ok', {0: 0, 1: 1, 2: 4}), ('Ok', {0: 1, 1: 0, 2: 4})),
    ('W3', 'sender is account 0', {0: 5, 1: 0}, {}, (0, 1, 2), 'newly_rejected',
     ('Ok', {0: 3, 1: 2}), ('Rejected', {0: 5, 1: 0})),
    ('W4', 'recipient is account 0', {0: 0, 1: 5}, {}, (1, 0, 2), 'newly_rejected',
     ('Ok', {0: 2, 1: 3}), ('Rejected', {0: 0, 1: 5})),
    ('W5', 'no account 0', {1: 5, 2: 0}, {}, (1, 2, 2), 'newly_rejected',
     ('Ok', {1: 3, 2: 2}), ('Rejected', {1: 5, 2: 0})),
    ('W6', 'insufficient funds under both', {0: 0, 1: 5, 2: 0}, {}, (1, 2, 6), 'unchanged',
     ('Rejected', {0: 0, 1: 5, 2: 0}), ('Rejected', {0: 0, 1: 5, 2: 0})),
]


def dmap(d):
    return 'map[' + ', '.join(f'{k} := {v}' for k, v in sorted(d.items())) + ']'


out = ['// GENERATED by gen_fee_witnesses.py (U413). Do not edit. Boundary witnesses for the fee-change spec diff.',
       '// Each lemma says: EVERY result that the old specification allows and EVERY result that the new one allows',
       '// for this state and request are the stated ones; and both specifications allow a result (non-vacuity).',
       'include "SpecDiffFee.dfy"', '', 'abstract module SpecDiffFeeWitnesses {', '  import D : SpecDiffFee', '']
rows = []
for name, title, bal, acc, (s, r, amt), kind, (oo, ob), (no, nb) in W:
    S = f'D.O.LedgerState({dmap(bal)}, map[])'
    R = f'D.O.TransferRequest({s}, {r}, {amt})'
    call = {'newly_rejected': f'D.NewlyRejectedIff({S}, {ID}, {R});\n    D.NewlyRejected({S}, {ID}, {R}, n, o, n\', o\');',
            'both_accept': f'D.BothAcceptResult({S}, {ID}, {R}, n, o, n\', o\');',
            'unchanged': f'D.UnchangedWhenOldDoesNotAccept({S}, {ID}, {R}, n, o, n\', o\');'}[kind]
    fresh_old = 'true' if oo == 'Ok' else 'false'
    out += [f'  // {name}: {title}. Kind: {kind}.',
            f'  lemma {name}(n: D.O.State, o: D.O.Outcome, n\': D.N.State, o\': D.N.Outcome)',
            f'    requires D.PostO({S}, {ID}, {R}, n, o)',
            f'    requires D.PostN(D.StateN({S}), {ID}, D.ReqN({R}), n\', o\')',
            f'    ensures n.balances.Keys == {{{", ".join(str(k) for k in sorted(bal))}}} && n\'.balances.Keys == n.balances.Keys',
            f'    ensures o == D.O.{oo} && ' + ' && '.join(f'n.balances[{k}] == {v}' for k, v in sorted(ob.items())),
            f'    ensures o\' == D.N.{no} && ' + ' && '.join(f'n\'.balances[{k}] == {v}' for k, v in sorted(nb.items())),
            '  {',
            f'    assert D.O.WellFormed({S});',
            f'    assert D.O.IsFreshValid({S}, {ID}, {R}) == {fresh_old};',
            f'    D.KeysOf({S}, {ID}, {R}, n, o, n\', o\');',
            (f'    D.NewFreshIff({S}, {ID}, {R});' if oo == 'Ok' else '    // old specification does not accept'),
            f'    {call}',
            '  }', '',
            f'  lemma {name}_NonVacuous()',
            f'    ensures exists n: D.O.State, o: D.O.Outcome :: D.PostO({S}, {ID}, {R}, n, o)',
            f'    ensures exists n\': D.N.State, o\': D.N.Outcome :: D.PostN(D.StateN({S}), {ID}, D.ReqN({R}), n\', o\')',
            '  {',
            f'    D.OldPostSatisfiable({S}, {ID}, {R});',
            f'    D.WellFormedCarries({S});',
            f'    D.NewPostSatisfiable(D.StateN({S}), {ID}, D.ReqN({R}));',
            '  }', '']
    rows.append({'witness': name, 'title': title, 'kind': kind, 'request_id': ID,
                 'pre_balances': {str(k): v for k, v in sorted(bal.items())},
                 'request': {'sender': s, 'recipient': r, 'amount': amt},
                 'old_spec': {'outcome': oo, 'balances': {str(k): v for k, v in sorted(ob.items())}},
                 'new_spec': {'outcome': no, 'balances': {str(k): v for k, v in sorted(nb.items())}},
                 'dafny_lemmas': [f'SpecDiffFeeWitnesses.{name}', f'SpecDiffFeeWitnesses.{name}_NonVacuous']})
out.append('}')
(HERE / 'SpecDiffFeeWitnesses.dfy').write_text('\n'.join(out) + '\n')
receipt = {
    'change': 'proposals/fees.md (no fee -> one-unit fee to account 0)',
    'old_spec': 'spec/LedgerSpec.dfy at c909a640, SHA-256 e9bdfd511d3cffb04c533dcc62252cabf84a825d5577ea5999d18bc25e0bda0f',
    'new_spec': 'spec/LedgerSpec.dfy (approved)',
    'status': 'DATA ONLY. Each row and each general statement is a Dafny lemma; see the run summary for checker exits.',
    'end_to_end': False,
    'general_statements': [
        {'lemma': 'SpecDiffFee.UnchangedWhenOldDoesNotAccept', 'text': 'Unchanged region: every retry and every request that the old spec rejects. Same state, same outcome.'},
        {'lemma': 'SpecDiffFee.FeeDeltaWhenBothAccept', 'text': 'Where both accept: the new result is the old result with one unit moved from the sender to account 0.'},
        {'lemma': 'SpecDiffFee.NewlyRejectedIff', 'text': 'Accepted by the old spec and rejected by the new one exactly when: no account 0, or sender is 0, or recipient is 0, or sender balance equals the amount.'},
        {'lemma': 'SpecDiffFee.ChangedWhenOldAccepts', 'text': 'Changed region: every request that the old spec accepts as a fresh transfer.'},
        {'lemma': 'SpecDiffFee.OldPostSatisfiable, SpecDiffFee.NewPostSatisfiable', 'text': 'Both specs allow a result for every well-formed state (statements above are not vacuous).'}],
    'boundary_witnesses': rows}
(HERE / 'records').mkdir(exist_ok=True)
(HERE / 'records/fee-change-receipt.json').write_text(json.dumps(receipt, indent=1, sort_keys=True) + '\n')
print(len(rows), 'witnesses written')
