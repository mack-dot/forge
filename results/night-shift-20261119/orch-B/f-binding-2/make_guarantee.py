    added = [x for x in ne if x not in oe]
    d.append('- Added %d edges (%s): %s.' % (len(added), counts(NEW, set(added)), ', '.join(added)))
    d.append('- Removed edges: %s. Retired assumptions: H3a-SER-INJECTIVE (false for the real token), BETA-DAFNY-HOL (split in three).' % (
        [x for x in oe if x not in ne] or 'none'))
    d.append('- Changed text without class change: T-V2B now SUPERSEDED by T-BYTES-R (retired_hypotheses H3a); U3 assumptions H3a -> H3d-B6, A4b; S7 -> BETA-VALUES/OPS/ORDER.')
