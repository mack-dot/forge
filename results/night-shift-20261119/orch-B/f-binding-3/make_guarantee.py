SHORT = {'MACHINE-CHECKED': 'MC', 'ASSUMPTION': 'ASM', 'TESTED-UNPROVED': 'TESTED', 'MISSING': 'MISSING',
         'CLAIMED, log missing': 'CLAIMED', 'UNKNOWN-TONIGHT': 'UNKNOWN'}
NSP = 'results/night-shift-20261119/orch-B/'


def short(p):
    for cut in ('results/night-shift-20261119/', 'results/m1b-routeA-20261119/attempt-0001/', 'proposals/'):
        if cut in p:
            return p.split(cut, 1)[1]
    return p


def pointer(e):
    if e.get('runs'):
        r = e['runs'][0]
        return '`%s` %s' % (short(r['log']), 'go exit 0' if r.get('exit_line_form') == 'hol-go-wrapper' else 'exit 0')
    if e.get('runs_not_counted'):
        r = e['runs_not_counted'][0]
        return '`%s` %s %s' % (short(r['log']), r.get('exit_line_form') or '', r.get('exit'))
    if e.get('prior_records'):
        return 'prior record only `%s`' % short(e['prior_records'][-1]['path'])
    if e.get('evidence'):
        return '`%s`' % short(e['evidence'][0])
    return 'assumptions: ' + (', '.join(e['assumptions']) or 'none named')


def counts(led, ids=None):
    es = [e for e in led['edges'] if ids is None or e['id'] in ids]
    c = Counter(e['class'] for e in es)
    return ', '.join('%s %d' % (SHORT[k], c.get(k, 0)) for k in CL) + ' (total %d)' % len(es)


def subs(ne, eid):
    s = [x for x in ne.values() if x.get('sub_of') == eid]
    return (' Sub: ' + ', '.join('%s %s' % (x['id'], SHORT[x['class']]) for x in s)) if s else ''


