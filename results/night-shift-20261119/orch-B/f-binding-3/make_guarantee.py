    # ---- diff summary
    d = ['# Diff against orch-B/f-binding-2/ASSURANCE_LEDGER.json (generated by make_guarantee.py)', '']
    for eid in ne:
        if eid in oe and oe[eid]['class'] != ne[eid]['class']:
            d.append('- %s: %s -> %s.' % (eid, SHORT[oe[eid]['class']], SHORT[ne[eid]['class']]))
    added = [x for x in ne if x not in oe]
    d.append('- Added %d edges (%s): %s.' % (len(added), counts(NEW, set(added)), ', '.join(added)))
    d.append('- Removed edges: %s.' % ([x for x in oe if x not in ne] or 'none'))
    oa = {a['id']: a for a in OLD['assumptions']}
    na = {a['id']: a for a in NEW['assumptions']}
    d.append('- Added assumptions (%d): %s.' % (len([x for x in na if x not in oa]), ', '.join(x for x in na if x not in oa)))
    d.append('- Newly retired: %s. Superseded for the hash core only (kept active for value-core edges): %s.' % (
        ', '.join(x for x in na if na[x].get('status') == 'retired' and oa.get(x, {}).get('status') != 'retired'),
        ', '.join(x for x in na if na[x].get('superseded_for'))))
    ch = [e for e in ne if e in oe and (ne[e]['assumptions'] != oe[e]['assumptions'] or ne[e]['statement'] != oe[e]['statement'])]
    d.append('- Changed text or assumptions without class change: %s.' % ', '.join(x for x in ch if ne[x]['class'] == oe[x]['class']))
    d.append('- Newly superseded: %s.' % ', '.join('%s by %s' % (x, ne[x]['superseded_by']) for x in ne
                                                  if ne[x].get('superseded_by') and oe.get(x, {}).get('superseded_by') != ne[x]['superseded_by']))
    d.append('- Rule changes (verifier and generator; none removed or weakened): CMD_ROOTS_MISMATCH, HOL_EXPLORE_RUN, SUPERSEDED_BAD without retired hypotheses; '
             'COMMAND_ROOT_MISMATCH now also needs the edge command .dfy set to equal the closure roots.')
    (HERE / 'DIFF_SUMMARY.md').write_text('\n'.join(d) + '\n')
    print('DIFF_SUMMARY.md lines', len(d))


