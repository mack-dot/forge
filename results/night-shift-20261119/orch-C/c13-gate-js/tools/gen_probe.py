#!/usr/bin/env python3
"""c13-gate-js: generate probe/Probe.dfy (literal and value semantics probe; NOT a gate submission).
Each probe Pnn is a compiled predicate. Lemma Check asserts every probe with its arguments: a verify run
shows which ones the VERIFIER holds true (a failing assert names its line). tools/run_probe.cjs runs the
same predicates in the compiled JavaScript with the same arguments. Any difference = verifier/runtime gap.
Raw control characters (CR, VT, FF, LS, NEL, TAB) are written as real bytes."""
import json, sys
CR, LF, VT, FF, TAB, LS, PS, NEL, BOM = '\r', '\n', '\x0b', '\x0c', '\t', '\u2028', '\u2029', '\x85', '\ufeff'
ASTRAL = '\U0001F600'
# (name, params, body, args for the lemma (Dafny text), args for Node (JSON-able tags))
P = [
 ('P01', '', '@"x' + CR + 'y" == "x\\ny"', '', []),
 ('P02', '', '|@"x' + CR + 'y"| == 3', '', []),
 ('P03', '', '@"x' + CR + 'y" == "x\\ry"', '', []),
 ('P04', '', '@"x' + CR + LF + 'y" == "x\\r\\ny"', '', []),
 ('P05', '', '@"x' + CR + CR + 'y" == "x\\n\\ny"', '', []),
 ('P06', '', '@"x' + CR + CR + LF + 'y" == "x\\n\\r\\ny"', '', []),
 ('P07', '', '"\\U{1F600}" == "' + ASTRAL + '"', '', []),
 ('P08', '', '|"' + ASTRAL + '"| == 1', '', []),
 ('P09', '', "'\\U{1F600}' == '" + ASTRAL + "'", '', []),
 ('P10', '', '|"\\U{10FFFF}"| == 1', '', []),
 ('P11', '', '|@"a' + LS + 'b"| == 3 && "a' + LS + 'b" == "a\\U{2028}b" && "a' + PS + 'b" == "a\\U{2029}b"', '', []),
 ('P12', '', '@"a' + TAB + 'b" == "a\\tb" && @"a' + FF + 'b" == "a\\U{000C}b" && @"a' + VT + 'b" == "a\\U{000B}b"', '', []),
 ('P13', '', '@"a""b" == "a\\"b" && @"\\" == "\\\\" && @"\\n" == "\\\\n"', '', []),
 ('P14', '', '|"\\0"| == 1 && "\\0" == "\\U{0}" && "\\01" == "\\U{0}1" && |"\\01"| == 2', '', []),
 ('P15', '', '"\\r" != "\\n" && |"\\r\\n"| == 2 && "\\\'" == "\'" && \'\\"\' == \'"\'', '', []),
 ('P16', '', '|"a' + NEL + 'b"| == 3 && "a' + NEL + 'b" == "a\\U{85}b" && |"' + BOM + '"| == 1', '', []),
 ('P17', '', '"\\U{1_F600}" == "\\U{1F600}"', '', []),
 ('P18', '', '9999999999999999999 - 9007199254740993 == 9990992800745259006', '', []),
 ('P19', '', '9999999999999999999 / 7 == 1428571428571428571 && 9999999999999999999 % 7 == 2 && 9999999999999999999 / -7 == -1428571428571428571 && 9999999999999999999 % -7 == 2', '', []),
 ('P20', '', '-9999999999999999999 / 7 == -1428571428571428572 && -9999999999999999999 % 7 == 5 && -9999999999999999999 / -7 == 1428571428571428572 && -9999999999999999999 % -7 == 5', '', []),
 ('P21', '', '9007199254740993 != 9007199254740992 && -9007199254740993 != -9007199254740992 && - -9007199254740993 == 9007199254740993', '', []),
 ('P22', 's: string', '|{s, "x"}| == 1', '"x"', ['str:x']),
 ('P23', 'a: int', '|{a, 1}| == 1 && |[a, 1]| == 2', '1', ['int:1']),
 ('P24', 'a: int', '|{a - 0, 9007199254740993}| == 1', '9007199254740993', ['int:9007199254740993']),
 ('P25', 's: string', "'" + ASTRAL + "' in s && s == \"" + ASTRAL + "\" && |s| == 1", '"' + ASTRAL + '"', ['str:' + ASTRAL]),
 ('P26', 'a: int', '[[a, 2], [3]] == [[1, 2], [3]] && (a, "q") == (1, "q") && {[a]} == {[1]}', '1', ['int:1']),
 ('P27', 's: string', 's in {"x", "x", "y"} && s in ["y", "x", "x"] && |{"x", "x", s}| == 1', '"x"', ['str:x']),
 ('P28', 'a: int', 'a % 7 == 5 && a / 7 == -1', '-2', ['int:-2']),
 ('P29', 'a: int, b: int', '0 <= a <= b < 10 && a == b == 3', '3, 3', ['int:3', 'int:3']),
 ('P30', 's: string', '|{s, @"x' + CR + 'y"}| == 1', '"x\\ny"', ['str:x\ny']),
 ('P31', 's: string', '|{s, @"x' + CR + 'y"}| == 2', '"x\\ry"', ['str:x\ry']),
 ('P32', '', "'\\U{1F600}' != '\\U{1F601}' && \"\\U{1F600}\" != \"\\U{D83D}\"", '', []),
]
which = sys.argv[1] if len(sys.argv) > 1 else 'all'
skip = set(sys.argv[2].split(',')) if len(sys.argv) > 2 else set()
out = ['// c13-gate-js probe (generated by tools/gen_probe.py). Not a gate submission.', 'module Probe {']
for n, ps, body, la, _ in P:
    if n in skip: continue
    out.append('  predicate %s(%s) { %s }' % (n, ps, body))
out.append('  lemma Check() {')
for n, ps, body, la, _ in P:
    if n in skip: continue
    out.append('    assert %s(%s);' % (n, la))
out.append('  }')
out.append('}')
open(sys.argv[3] if len(sys.argv) > 3 else 'probe/Probe.dfy', 'w', newline='').write('\n'.join(out) + '\n')
json.dump([(n, a) for n, _, _, _, a in P if n not in skip], open('probe/probe_args.json', 'w'))
